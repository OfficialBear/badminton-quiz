export type RandomSource = () => number

/** Fisher–Yates shuffle driven by an injectable random source (0..1). */
export function shuffleWith<T>(items: readonly T[], rng: RandomSource): T[] {
  const result = [...items]
  for (let i = result.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rng() * (i + 1))
    const a = result[i]
    const b = result[j]
    if (a !== undefined && b !== undefined) {
      result[i] = b
      result[j] = a
    }
  }
  return result
}

export function shuffle<T>(items: readonly T[]): T[] {
  return shuffleWith(items, Math.random)
}

/** Deterministic mulberry32 PRNG so tests can reproduce sampling exactly. */
export function createSeededRandom(seed: number): RandomSource {
  let state = seed >>> 0
  return () => {
    state = (state + 0x6d2b79f5) >>> 0
    let t = state
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}
